def d5sd(image):
    if len(image) < 0x1920000:
        raise ValueError('PS4 eboot: image too small')
    blocs = []; hachage = {}; compte = {}
    for ev, a in NOMS:
        hachage[ev] = struct.unpack_from('<I', image, a)[0]; blocs.append(('N%d' % ev, 1, image[a + 4:a + 32]))
    for nom, a, n in LISTES:
        ps4 = struct.unpack_from('<%dQ' % n, image, a)
        if not all(MAPC.get(c) for c in ps4):
            raise ValueError('PS4 eboot: unexpected Crimson effect creator')
        compte[nom] = n; blocs.append((nom, 4, struct.pack('<%dI' % n, *(MAPC[c] for c in ps4))))
    index = {nom: i for i, (nom, _, _) in enumerate(blocs)}
    parts = bytearray()
    for ev, desc, groupes, attache, rendu in PARTIES:
        v = [ev, desc, hachage[ev], index['N%d' % ev]]
        for k in range(4):
            v += [groupes[k][0], groupes[k][1], index[groupes[k][2]], compte[groupes[k][2]]] if k < len(groupes) else [0, 0, 0xFFFFFFFF, 0]
        parts += struct.pack('<20I', *v) + bytes((attache, rendu, 0, 0))
    blocs.append(('GenericParts', 84, bytes(parts)))
    out = bytearray(b'D5SD' + struct.pack('<II', 1, len(blocs)))
    for nom, el, d in blocs:
        b = nom.encode('ascii'); out += struct.pack('<H', len(b)) + b + struct.pack('<II', el, len(d)) + d
    return bytes(out)
